export function getCurrencyMeta(
  currencyCode: string,
  currencies: CurrencyConfig[] = DEFAULT_CURRENCIES
): CurrencyConfig {
  return (
    currencies.find((c) => c.code === currencyCode) || {
      code: currencyCode || 'KES',
      name: currencyCode || 'Kenyan Shilling',
      symbol: currencyCode || 'KES',
      decimals: currencyCode === 'USD' || currencyCode === 'USDT' || currencyCode === 'NGN' ? 2 : 0,
      enabled: true,
    }
  );
}

export function getCountryName(
  countryCode: string | undefined,
  countries: CountryFinancialConfig[] = DEFAULT_COUNTRIES
): string {
  const code = countryCode || 'KE';
  return countries.find((c) => c.code === code)?.name || code;
}
